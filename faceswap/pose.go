func (e *Engine) yaw(ctx context.Context, src fetchFn, box [4]float64) (float64, error) {
	s, err := e.session(modelLmk)
	if err != nil {
		return 0, err
	}
	w, h := box[2]-box[0], box[3]-box[1]
	cx, cy := (box[0]+box[2])/2, (box[1]+box[3])/2
	sc := lmkSize / (math.Max(w, h) * 1.5)
	m := affine{sc, 0, lmkSize/2 - cx*sc, 0, sc, lmkSize/2 - cy*sc}
	crop := warp(src, 3, m, lmkSize, lmkSize, true)
	outs, _, err := onnxrt.Run(ctx, s, onnxrt.Input{Name: s.Inputs[0].Name, Shape: []int64{1, 3, lmkSize, lmkSize}, Data: chw(crop, func(v float32, _ int) float32 { return v })})
	if err != nil {
		return 0, fmt.Errorf("landmark: %w", err)
	}
	pred := outs[0]
	if len(pred) < 68*3 || len(pred)%3 != 0 {
		return 0, fmt.Errorf("landmark: %d outputs", len(pred))
	}
	pred = pred[len(pred)-68*3:]
	inv := m.invert()
	zs := math.Hypot(inv[0], inv[1])
	var pts [68][3]float64
	for i := range pts {
		x := (float64(pred[3*i]) + 1) * lmkSize / 2
		y := (float64(pred[3*i+1]) + 1) * lmkSize / 2
		pts[i][0], pts[i][1] = inv.apply(x, y)
		pts[i][2] = float64(pred[3*i+2]) * lmkSize / 2 * zs
	}
	return yawFromLandmarks(pts), nil
}

func yawFromLandmarks(pts [68][3]float64) float64 {
	var ata [4][4]float64
	var atb [4][3]float64
	for i := 0; i < 68; i++ {
		x := [4]float64{meanShape68[3*i], meanShape68[3*i+1], meanShape68[3*i+2], 1}
		for r := 0; r < 4; r++ {
			for c := 0; c < 4; c++ {
				ata[r][c] += x[r] * x[c]
			}
			for c := 0; c < 3; c++ {
				atb[r][c] += x[r] * pts[i][c]
			}
		}
	}
	p := solve4(ata, atb)
	r1 := [3]float64{p[0][0], p[1][0], p[2][0]}
	r2 := [3]float64{p[0][1], p[1][1], p[2][1]}
	n1, n2 := math.Sqrt(dot3(r1, r1)), math.Sqrt(dot3(r2, r2))
	for k := 0; k < 3; k++ {
		r1[k] /= n1
		r2[k] /= n2
	}
	r3 := [3]float64{r1[1]*r2[2] - r1[2]*r2[1], r1[2]*r2[0] - r1[0]*r2[2], r1[0]*r2[1] - r1[1]*r2[0]}
	sy := math.Hypot(r1[0], r2[0])
	return math.Atan2(-r3[0], sy) * 180 / math.Pi
}

func dot3(a, b [3]float64) float64 { return a[0]*b[0] + a[1]*b[1] + a[2]*b[2] }

func solve4(a [4][4]float64, b [4][3]float64) [4][3]float64 {
	for c := 0; c < 4; c++ {
		piv := c
		for r := c + 1; r < 4; r++ {
			if math.Abs(a[r][c]) > math.Abs(a[piv][c]) {
				piv = r
			}
		}
		a[c], a[piv] = a[piv], a[c]
		b[c], b[piv] = b[piv], b[c]
		for r := 0; r < 4; r++ {
			if r == c || a[c][c] == 0 {
				continue
			}
			f := a[r][c] / a[c][c]
			for k := 0; k < 4; k++ {
				a[r][k] -= f * a[c][k]
			}
			for k := 0; k < 3; k++ {
				b[r][k] -= f * b[c][k]
			}
		}
	}
	for r := 0; r < 4; r++ {
		for k := 0; k < 3 && a[r][r] != 0; k++ {
			b[r][k] /= a[r][r]
		}
	}
	return b
}
